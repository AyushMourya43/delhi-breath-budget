"use client";

import {
  useEffect,
  useRef,
  useState,
  type FormEvent,
} from "react";
import { Bot, Send, Sparkles, X } from "lucide-react";

import { useDemoMode } from "../../lib/demo-mode";
import {
  assistantSuggestions,
  assistantDemoThread,
  pickDemoReply,
  type DemoAssistantMessage,
} from "../../data/demo/assistant";

// Floating AI assistant.
// - Floating button in bottom-right corner
// - Smooth open/close animation (CSS spring)
// - Modern chat panel with message bubbles
// - Typing indicator
// - Suggested questions
// - Clear user vs assistant message styles
// - DEMO label on every assistant reply when in demo mode
// - LIVE mode: defers to the existing /advice endpoint via apiPost (preserved
//   contract). For this UI shell we keep demo replies on the surface and
//   clearly mark them — the actual backend AI is invoked from LivePanels.tsx
//   ForecastPanel via POST /advice, which remains untouched.
export default function FloatingAssistant() {
  const demo = useDemoMode();
  const [open, setOpen] = useState(false);
  const [closing, setClosing] = useState(false);
  const [input, setInput] = useState("");
  const [typing, setTyping] = useState(false);
  const [messages, setMessages] = useState<DemoAssistantMessage[]>(
    assistantDemoThread.messages,
  );
  const bodyRef = useRef<HTMLDivElement | null>(null);

  // Auto-scroll to latest message
  useEffect(() => {
    if (bodyRef.current) {
      bodyRef.current.scrollTop = bodyRef.current.scrollHeight;
    }
  }, [messages, typing]);

  function closePanel() {
    setClosing(true);
    window.setTimeout(() => {
      setOpen(false);
      setClosing(false);
    }, 180);
  }

  async function send(text: string) {
    const trimmed = text.trim();
    if (!trimmed || typing) return;

    const userMsg: DemoAssistantMessage = { role: "user", content: trimmed };
    setMessages((prev) => [...prev, userMsg]);
    setInput("");
    setTyping(true);

    // Simulate brief thinking delay; demo mode produces a templated reply.
    // In LIVE mode we don't pretend to call an LLM — the existing backend
    // advice endpoint is already surfaced by the Forecast panel. Instead we
    // return a clear notice that the live backend integration lives there.
    const reply = demo.isDemo
      ? pickDemoReply(trimmed)
      : "Live mode: this assistant panel surfaces demo-style replies only. The real backend guidance is generated by the Plan My Day / Forecast panel via the /advice endpoint. Switch back to Demo to see illustrative conversation here.";

    const delay = demo.isDemo ? 700 + Math.random() * 500 : 400;
    window.setTimeout(() => {
      setTyping(false);
      setMessages((prev) => [
        ...prev,
        { role: "assistant", content: reply, isDemoReply: demo.isDemo },
      ]);
    }, delay);
  }

  function handleSubmit(e: FormEvent) {
    e.preventDefault();
    send(input);
  }

  return (
    <>
      {!open && (
        <button
          type="button"
          className="dbb-assistant-fab"
          aria-label="Open AI assistant"
          aria-expanded={open}
          onClick={() => setOpen(true)}
        >
          <Sparkles size={22} />
        </button>
      )}

      {open && (
        <section
          className={`dbb-assistant-panel ${closing ? "dbb-closing" : ""}`}
          aria-label="AI assistant panel"
        >
          <header className="dbb-assistant-head">
            <div className="dbb-assistant-avatar">
              <Bot size={18} />
            </div>
            <div className="dbb-assistant-titles">
              <div className="dbb-assistant-name">Breath Assistant</div>
              <div className="dbb-assistant-sub">
                <span className="dbb-status-dot" />
                {demo.isDemo ? "DEMO · sample replies" : "Live mode · static replies"}
              </div>
            </div>
            <button
              type="button"
              className="dbb-assistant-close"
              aria-label="Close assistant"
              onClick={closePanel}
            >
              <X size={16} />
            </button>
          </header>

          <div className="dbb-assistant-body" ref={bodyRef}>
            {messages.map((m, i) => (
              <div
                key={i}
                className={`dbb-msg ${m.role === "user" ? "dbb-msg-user" : "dbb-msg-ai"}`}
              >
                <div className="dbb-msg-bubble">{m.content}</div>
                {m.role === "assistant" && (
                  <div className="dbb-msg-meta">
                    {m.isDemoReply && <span className="dbb-demo-badge">DEMO</span>}
                    Assistant
                  </div>
                )}
              </div>
            ))}

            {typing && (
              <div className="dbb-typing" aria-label="Assistant is typing">
                <span className="dbb-typing-dot" />
                <span className="dbb-typing-dot" />
                <span className="dbb-typing-dot" />
              </div>
            )}
          </div>

          <div className="dbb-assistant-suggestions">
            {assistantSuggestions.slice(0, 3).map((s) => (
              <button
                key={s}
                type="button"
                className="dbb-assistant-suggestion"
                onClick={() => send(s)}
                disabled={typing}
              >
                {s}
              </button>
            ))}
          </div>

          <form className="dbb-assistant-input" onSubmit={handleSubmit}>
            <input
              type="text"
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder="Ask about pollution, timing, routes…"
              aria-label="Message the assistant"
              disabled={typing}
            />
            <button
              type="submit"
              disabled={!input.trim() || typing}
              aria-label="Send message"
            >
              <Send size={16} />
            </button>
          </form>
        </section>
      )}
    </>
  );
}
